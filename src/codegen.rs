const PARSE_PREFIX_METHOD: &str = "    #[inline]\n    pub fn parse_prefix(body: &[u8]) -> Option<(&Self, &[u8])> {\n        Ref::<_, Self>::from_prefix(body)\n            .ok()\n            .map(|(r, b)| (Ref::into_ref(r), b))\n    }\n";

#[derive(Debug, Error)]
pub enum CodegenError {
    #[error("{0}")]
    InvalidSchema(String),
}

fn push_doc_comment(buf: &mut String, text: &str) {
    for line in text.lines() {
        buf.push_str("/// ");
        buf.push_str(line.trim_end());
        buf.push('\n');
    }
}

fn maybe_doc_comment(buf: &mut String, desc: &Option<String>) {
    if let Some(text) = desc.as_deref() {
        push_doc_comment(buf, text);
    }
}

const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "union", "_",
];

fn sanitize_ident(name: &str) -> String {
    let mut out = String::with_capacity(name.len().max(1));
    let mut prev_underscore = false;
    for (idx, ch) in name.chars().enumerate() {
        let valid = if idx == 0 {
            ch == '_' || ch.is_ascii_alphabetic()
        } else {
            ch == '_' || ch.is_ascii_alphanumeric()
        };
        if valid {
            out.push(ch);
            prev_underscore = false;
        } else if !prev_underscore {
            out.push('_');
            prev_underscore = true;
        }
    }
    if out.is_empty() {
        out.push('_');
    }
    if out
        .as_bytes()
        .first()
        .map(|b| b.is_ascii_digit())
        .unwrap_or(false)
    {
        out.insert(0, '_');
    }
    if RUST_KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    if out == "_" {
        out.push('_');
    }
    out
}

fn snake_ident(name: &str) -> String {
    sanitize_ident(&name.to_snake_case())
}

fn type_ident(name: &str) -> String {
    sanitize_ident(name)
}

fn const_ident(name: &str) -> String {
    upper_ident(&snake_ident(name))
}

fn variant_ident(name: &str) -> String {
    sanitize_ident(&name.to_upper_camel_case())
}

fn type_with_suffix(name: &str, suffix: &str) -> String {
    format!("{}{}", type_ident(name), suffix)
}

fn enum_name(name: &str) -> String {
    type_with_suffix(name, "Enum")
}

fn snake_with_suffix(name: &str, suffix: &str) -> String {
    let mut out = name.to_string();
    if !out.ends_with('_') {
        out.push('_');
    }
    out.push_str(suffix.trim_start_matches('_'));
    sanitize_ident(&out)
}

fn upper_ident(name: &str) -> String {
    let mut out = String::new();
    let mut prev_underscore = false;
    for ch in name.chars() {
        let mapped = if ch.is_ascii_alphanumeric() {
            ch.to_ascii_uppercase()
        } else {
            '_'
        };
        if mapped == '_' {
            if !prev_underscore {
                out.push('_');
                prev_underscore = true;
            }
        } else {
            out.push(mapped);
            prev_underscore = false;
        }
    }
    sanitize_ident(&out)
}

struct NameScope {
    scope: String,
    used: HashMap<String, String>,
}

impl NameScope {
    fn new(scope: impl Into<String>) -> Self {
        Self {
            scope: scope.into(),
            used: HashMap::new(),
        }
    }

    fn reserve(&mut self, ident: &str, desc: &str) {
        self.used.insert(ident.to_string(), desc.to_string());
    }

    fn claim(&mut self, ident: String, desc: String) -> Result<(), CodegenError> {
        if let Some(prev) = self.used.insert(ident.clone(), desc.clone()) {
            return Err(CodegenError::InvalidSchema(format!(
                "identifier collision in {} after Rust sanitization: {} and {} both map to '{}'",
                self.scope, prev, desc, ident
            )));
        }
        Ok(())
    }
}

fn push_file_preamble(buf: &mut String, opts: &GeneratorOptions, default_allow: Option<&str>) {
    if let Some(allow) = opts.allow_attr.as_deref() {
        buf.push_str(allow);
        if !allow.ends_with('\n') {
            buf.push('\n');
        }
    }
    buf.push_str("// Automatically generated by sbe_gen.\n");
    if let Some(allow) = default_allow {
        buf.push_str(allow);
        if !allow.ends_with('\n') {
            buf.push('\n');
        }
    }
}

fn message_fields(msg: &Message) -> Vec<&Field> {
    msg.members
        .iter()
        .filter_map(|m| {
            if let MessageMember::Field(f) = m {
                Some(f)
            } else {
                None
            }
        })
        .collect()
}

