fn collect_used_types(schema: &Schema) -> HashSet<String> {
    let mut used = HashSet::new();
    for msg in &schema.messages {
        collect_used_types_in_message(msg, &mut used);
    }
    for ty in schema.types.values() {
        if let TypeDef::Composite { fields, .. } = ty {
            for field in fields {
                if let CompositeField::Ref { ty, .. } = field {
                    used.insert(ty.clone());
                }
            }
        }
    }
    used
}

fn collect_schema_fields(schema: &Schema) -> Vec<&Field> {
    let mut out = Vec::new();
    for msg in &schema.messages {
        collect_message_fields(msg, &mut out);
    }
    out
}

fn collect_message_fields<'a>(msg: &'a Message, out: &mut Vec<&'a Field>) {
    for member in &msg.members {
        match member {
            MessageMember::Field(field) => out.push(field),
            MessageMember::Group(group) => collect_group_fields(group, out),
            MessageMember::Data(_) => {}
        }
    }
}

fn collect_group_fields<'a>(group: &'a Group, out: &mut Vec<&'a Field>) {
    for member in &group.members {
        match member {
            GroupMember::Field(field) => out.push(field),
            GroupMember::Group(nested) => collect_group_fields(nested, out),
            GroupMember::Data(_) => {}
        }
    }
}

fn constant_type_alias_from_schema(type_name: &str, schema: &Schema) -> Option<String> {
    let mut candidates = HashSet::new();
    for field in collect_schema_fields(schema) {
        if field.ty != type_name {
            continue;
        }
        if let Some(value_ref) = &field.value_ref
            && let Some((ty, _)) = value_ref.split_once('.')
            && ty != type_name
            && let Some(td) = schema.types.get(ty)
            && !matches!(td, TypeDef::Composite { .. })
        {
            candidates.insert(ty.to_string());
        }
        if field.name != type_name
            && let Some(td) = schema.types.get(&field.name)
            && !matches!(td, TypeDef::Composite { .. })
        {
            candidates.insert(field.name.clone());
        }
    }
    if candidates.len() == 1 {
        candidates.into_iter().next()
    } else {
        None
    }
}

fn collect_used_types_in_message(msg: &Message, used: &mut HashSet<String>) {
    for member in &msg.members {
        match member {
            MessageMember::Field(field) => {
                used.insert(field.ty.clone());
            }
            MessageMember::Group(group) => collect_used_types_in_group(group, used),
            MessageMember::Data(data) => {
                used.insert(data.ty.clone());
            }
        }
    }
}

fn collect_used_types_in_group(group: &Group, used: &mut HashSet<String>) {
    used.insert(group.dimension_type.clone());
    for member in &group.members {
        match member {
            GroupMember::Field(field) => {
                used.insert(field.ty.clone());
            }
            GroupMember::Group(nested) => collect_used_types_in_group(nested, used),
            GroupMember::Data(data) => {
                used.insert(data.ty.clone());
            }
        }
    }
}

fn group_has_var_data(g: &Group) -> bool {
    if !group_data(g).is_empty() {
        return true;
    }
    for sub in group_groups(g) {
        if group_has_var_data(sub) {
            return true;
        }
    }
    false
}

fn validate_schema_types(schema: &Schema, opts: &GeneratorOptions) -> Result<(), CodegenError> {
    for msg in &schema.messages {
        validate_message_types(msg, schema, opts)?;
    }
    Ok(())
}

fn validate_message_types(
    msg: &Message,
    schema: &Schema,
    opts: &GeneratorOptions,
) -> Result<(), CodegenError> {
    for member in &msg.members {
        match member {
            MessageMember::Field(field) => {
                let scope = format!("message '{}' field '{}'", msg.name, field.name);
                validate_field_type(field, schema, opts, &scope)?;
            }
            MessageMember::Group(group) => {
                let scope = format!("message '{}' group '{}'", msg.name, group.name);
                validate_group_types(group, schema, opts, &scope)?;
            }
            MessageMember::Data(data) => {
                let scope = format!("message '{}' data '{}'", msg.name, data.name);
                validate_var_data_type(data, schema, &scope)?;
            }
        }
    }
    Ok(())
}

fn validate_group_types(
    group: &Group,
    schema: &Schema,
    opts: &GeneratorOptions,
    scope: &str,
) -> Result<(), CodegenError> {
    let dims = dimension_fields(schema, &group.dimension_type, opts);
    if !is_supported_dimension_int_type(&dims.block_field_ty) {
        return Err(CodegenError::InvalidSchema(format!(
            "unsupported blockLength type '{}' in {}",
            dims.block_field_ty, scope
        )));
    }
    if !is_supported_dimension_int_type(&dims.count_field_ty) {
        return Err(CodegenError::InvalidSchema(format!(
            "unsupported numInGroup/count type '{}' in {}",
            dims.count_field_ty, scope
        )));
    }

    for member in &group.members {
        match member {
            GroupMember::Field(field) => {
                let field_scope = format!("{scope} field '{}'", field.name);
                validate_field_type(field, schema, opts, &field_scope)?;
            }
            GroupMember::Group(nested) => {
                let nested_scope = format!("{scope} group '{}'", nested.name);
                validate_group_types(nested, schema, opts, &nested_scope)?;
            }
            GroupMember::Data(data) => {
                let data_scope = format!("{scope} data '{}'", data.name);
                validate_var_data_type(data, schema, &data_scope)?;
            }
        }
    }
    Ok(())
}

fn validate_var_data_type(
    data: &VarDataField,
    schema: &Schema,
    scope: &str,
) -> Result<(), CodegenError> {
    if try_length_kind_for_data(&data.ty, schema).is_none() {
        return Err(CodegenError::InvalidSchema(format!(
            "unsupported var-data length type '{}' for {}",
            data.ty, scope
        )));
    }
    Ok(())
}

fn is_supported_dimension_int_type(ty: &str) -> bool {
    matches!(
        ty.rsplit("::").next().unwrap_or(ty),
        "u8" | "i8"
            | "u16"
            | "i16"
            | "u32"
            | "i32"
            | "u64"
            | "i64"
            | "U16"
            | "I16"
            | "U32"
            | "I32"
            | "U64"
            | "I64"
    )
}

fn validate_field_type(
    field: &Field,
    schema: &Schema,
    opts: &GeneratorOptions,
    scope: &str,
) -> Result<(), CodegenError> {
    if resolve_type(&field.ty, schema, opts, field.byte_order.as_deref()).is_none() {
        return Err(CodegenError::InvalidSchema(format!(
            "unsupported field type '{}' for {}",
            field.ty, scope
        )));
    }
    let mut visiting = Vec::new();
    validate_type_reference(&field.ty, schema, opts, scope, &mut visiting)
}

fn validate_type_reference(
    ty: &str,
    schema: &Schema,
    opts: &GeneratorOptions,
    scope: &str,
    visiting: &mut Vec<String>,
) -> Result<(), CodegenError> {
    if primitive_to_rust(ty, opts).is_some() {
        return Ok(());
    }

    if visiting.iter().any(|seen| seen == ty) {
        let mut cycle = visiting.clone();
        cycle.push(ty.to_string());
        return Err(CodegenError::InvalidSchema(format!(
            "cyclic type reference in {}: {}",
            scope,
            cycle.join(" -> ")
        )));
    }

    let Some(def) = schema.types.get(ty) else {
        return Err(CodegenError::InvalidSchema(format!(
            "unknown type '{}' referenced by {}",
            ty, scope
        )));
    };

    visiting.push(ty.to_string());
    let result = match def {
        TypeDef::Primitive { primitive, .. } => {
            if primitive_to_rust(primitive, opts).is_none() {
                Err(CodegenError::InvalidSchema(format!(
                    "unsupported primitive '{}' in type '{}' used by {}",
                    primitive, ty, scope
                )))
            } else {
                Ok(())
            }
        }
        TypeDef::Enum { encoding, .. } | TypeDef::Set { encoding, .. } => {
            let Some(primitive) = encoding_primitive(encoding, &schema.types) else {
                return Err(CodegenError::InvalidSchema(format!(
                    "unsupported encoding type '{}' in '{}' used by {}",
                    encoding, ty, scope
                )));
            };
            if primitive_to_rust(&primitive, opts).is_none() {
                Err(CodegenError::InvalidSchema(format!(
                    "unsupported primitive '{}' in encoding '{}' used by {}",
                    primitive, ty, scope
                )))
            } else {
                Ok(())
            }
        }
        TypeDef::Composite { name, fields, .. } => {
            for field in fields {
                match field {
                    CompositeField::Type {
                        name: field_name,
                        primitive,
                        ..
                    } => {
                        if primitive_to_rust(primitive, opts).is_none() {
                            return Err(CodegenError::InvalidSchema(format!(
                                "unsupported primitive '{}' in composite '{}' field '{}' used by {}",
                                primitive, name, field_name, scope
                            )));
                        }
                    }
                    CompositeField::Ref {
                        name: field_name,
                        ty: ref_ty,
                    } => {
                        let ref_scope =
                            format!("{} via composite '{}' field '{}'", scope, name, field_name);
                        validate_type_reference(ref_ty, schema, opts, &ref_scope, visiting)?;
                    }
                }
            }
            Ok(())
        }
    };
    visiting.pop();
    result
}

fn type_def_name(def: &TypeDef) -> &str {
    match def {
        TypeDef::Primitive { name, .. } => name,
        TypeDef::Enum { name, .. } => name,
        TypeDef::Set { name, .. } => name,
        TypeDef::Composite { name, .. } => name,
    }
}

